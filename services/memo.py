"""Deterministic submission-memo drafts, one per recommended action.

The memo is the artifact a human approves before anything leaves the
brokerage. It is generated from the triage evidence only — no invented
facts, no model prose. Same inputs always produce the same memo.
"""


def draft_memo(sub, completeness, appetite, flags, band_result, recommendation):
    lines = []
    a = recommendation["action"]
    lines.append(f"SUBMISSION TRIAGE MEMO — {sub['submission_id']}")
    lines.append(f"Applicant profile: age idx {sub['age']}, BMI idx {sub['bmi']}, "
                 f"medical evidence {sub['med_answered']}/89 fields answered")
    lines.append(f"Recommended action: {a}")
    lines.append("")
    lines.append("WHY")
    for r in recommendation["rationale"]:
        lines.append(f"- {r}")
    lines.append("")
    lines.append(f"PACKET COMPLETENESS: {completeness['completeness_pct']}% "
                 f"({completeness['fields_present']}/{completeness['fields_required']} fields)")
    if completeness["missing_items"]:
        lines.append("Missing items:")
        for m in completeness["missing_items"][:12]:
            lines.append(f"  - [{m['document']}] {m['label']}: {m['field']}")
        if len(completeness["missing_items"]) > 12:
            lines.append(f"  ... and {len(completeness['missing_items']) - 12} more")
    lines.append("")
    lines.append(f"APPETITE FIT: {appetite['fit_score']}/100")
    for c in appetite["checks"]:
        mark = "PASS" if c["passed"] else "FAIL"
        lines.append(f"  [{mark}] {c['code']} {c['label']}: {c['detail']}")
    lines.append("")
    lines.append(f"RISK BAND: {band_result['band']}/8 (8 = lowest risk, 1 = highest risk)")
    lines.append(f"  {band_result['explanation']}")
    if flags:
        lines.append("")
        lines.append("FLAGS:")
        for f in flags:
            lines.append(f"  - {f['code']} {f['label']}: {f['detail']}")
    lines.append("")
    lines.append("NEXT STEPS (human-gated — nothing is sent automatically)")
    for i, s in enumerate(recommendation["next_steps"], 1):
        lines.append(f"  {i}. {s}")
    lines.append("")
    lines.append("Generated by FirstLook triage (deterministic rules, no LLM). "
                 "A licensed broker must approve before any client communication.")
    return "\n".join(lines)
